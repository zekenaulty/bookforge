def _observed_action_options(workspace: Path, book_id: str) -> Dict[str, Any]:
    observed: Dict[str, Any] = {}
    selectors = [
        ScopeSelector(book_id=book_id),
        ScopeSelector(book_id=book_id, chapter=1, section=1),
        ScopeSelector(book_id=book_id, chapter=1, scene=1),
        ScopeSelector(book_id=book_id, branch_id="__capability_projection_probe__"),
        ScopeSelector(book_id=book_id, branch_id="__capability_projection_probe__", chapter=1, scene=1),
        ScopeSelector(book_id=book_id, fork_group_id="__capability_projection_probe__"),
        ScopeSelector(book_id="__book_intents__", workflow_family="book_intent"),
    ]
    for selector in selectors:
        try:
            for option in list_execution_options(workspace, selector, prefer_emitted=False):
                observed.setdefault(option.action, option)
        except Exception:
            continue
    return observed


def _merge_observed_action_spec(spec: CapabilityDescriptor, option: Any) -> CapabilityDescriptor:
    if option is None:
        return spec
    details = dict(spec.details)
    if option.workflow_family and "workflow_family" not in details:
        details["workflow_family"] = option.workflow_family
    details["observed_from_execution_option"] = True
    return CapabilityDescriptor(
        capability_id=spec.capability_id,
        human_label=option.summary or spec.human_label,
        unit_type=spec.unit_type,
        capability_type=spec.capability_type,
        implementation_status=spec.implementation_status,
        action_key=spec.action_key,
        query_key=spec.query_key,
        supported_scope_kinds=list(spec.supported_scope_kinds),
        required_selector_shape=list(option.selector_requirements or spec.required_selector_shape),
        branch_policy=option.branch_policy or spec.branch_policy,
        mutation_class=spec.mutation_class,
        approval_required=spec.approval_required,
        readiness_source=spec.readiness_source,
        expected_receipt_type=spec.expected_receipt_type,
        process_area=spec.process_area,
        produced_artifact_statuses=list(spec.produced_artifact_statuses),
        legal_next_action_relationships=list(spec.legal_next_action_relationships),
        refusal_semantics=spec.refusal_semantics,
        child_actions=list(spec.child_actions),
        evidence_sources=list(spec.evidence_sources),
        details=details,
    )


def get_capability_projection(workspace: Optional[Path | str] = None, book_id: Optional[str] = None) -> CapabilityProjection:
    observed: Dict[str, Any] = {}
    projection_source = "static_registry"
    if workspace is not None and book_id:
        observed = _observed_action_options(Path(workspace), str(book_id))
        if observed:
            projection_source = "static_registry+execution_options"

    capabilities: List[CapabilityDescriptor] = []
    for action_key in sorted(ACTION_CAPABILITY_SPECS):
        capabilities.append(_merge_observed_action_spec(ACTION_CAPABILITY_SPECS[action_key], observed.get(action_key)))
    capabilities.extend(QUERY_CAPABILITY_SPECS)
    capabilities.extend(READINESS_CAPABILITY_SPECS)
    capabilities.extend(DESIGNED_GAP_CAPABILITIES)
    scope_kinds = sorted({scope for capability in capabilities for scope in capability.supported_scope_kinds})
    process_areas = sorted({capability.process_area for capability in capabilities if capability.process_area})
    return CapabilityProjection(
        capabilities=capabilities,
        projection_source=projection_source,
        details={
            "static_action_count": len(ACTION_CAPABILITY_SPECS),
            "observed_action_count": len(observed),
            "unprojected_observed_actions": sorted(set(observed) - set(ACTION_CAPABILITY_SPECS)),
            "query_count": len(QUERY_CAPABILITY_SPECS),
            "readiness_count": len(READINESS_CAPABILITY_SPECS),
            "designed_gap_count": len(DESIGNED_GAP_CAPABILITIES),
            "scope_kinds": scope_kinds,
            "process_areas": process_areas,
            "static_dynamic_boundary": "Capability descriptors are static. Use readiness and legal-next-action queries for a selected scope.",
        },
    )
