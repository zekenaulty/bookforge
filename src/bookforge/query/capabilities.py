def _evidence(source_type: str, reference: str, note: Optional[str] = None) -> CapabilityEvidenceSource:
    return CapabilityEvidenceSource(source_type=source_type, reference=reference, note=note)


def _refusal(mode: str, *codes: str, message: Optional[str] = None) -> CapabilityRefusalSemantics:
    return CapabilityRefusalSemantics(
        refusal_mode=mode,
        refusal_reason_codes=[code for code in codes if code],
        human_message=message,
    )


def _infer_process_area(key: str, workflow_family: Optional[str] = None) -> str:
    key = str(key or "")
    if workflow_family == "recovery_import" or "recovery" in key or key in {"quarantine_artifacts", "normalize_outline_scope", "invalidate_scope_outputs", "rebuild_state_scope", "redraft_scope"}:
        return "recovery"
    if "outline" in key or workflow_family in {"deep_outline", "thin_outline", "section_local_outline"} or "section_lineage" in key:
        return "outline"
    if "branch" in key or "assembly" in key or "fork" in key:
        return "branching"
    if "appearance" in key or "setting" in key or "context_projection" in key or "thought_context" in key:
        return "projection_layers"
    if "reader" in key or "manuscript" in key or "compile" in key or "export" in key:
        return "reader_output"
    if "author" in key:
        return "author_assets"
    if "visual" in key or "image" in key or "background_layer" in key or "character_reference" in key:
        return "visual_assets"
    if "intent" in key or "synopsis" in key or "book_seed" in key:
        return "book_intent"
    if "scene" in key or "write" in key or "lint" in key or "repair" in key or "chapter" in key or workflow_family == "section_write":
        return "writing"
    if "integrity" in key or "continuity" in key or "workflow" in key or "workspace" in key:
        return "diagnostics"
    return "engine"


def _action_spec(
    action_key: str,
    label: str,
    *,
    unit_type: str = "primitive_action",
    capability_type: str = "action",
    scopes: Iterable[str],
    selector_shape: Iterable[str],
    branch_policy: str,
    mutation_class: str,
    workflow_family: Optional[str] = None,
    approval_required: bool = False,
    readiness_source: Optional[str] = "list_execution_options",
    expected_receipt_type: str = "execution_result_v1",
    artifact_statuses: Iterable[str] = (),
    relationships: Iterable[str] = (),
    child_actions: Iterable[str] = (),
    process_area: Optional[str] = None,
    details: Optional[Dict[str, Any]] = None,
) -> CapabilityDescriptor:
    merged_details = dict(details or {})
    if workflow_family:
        merged_details["workflow_family"] = workflow_family
    return CapabilityDescriptor(
        capability_id=f"action.{action_key}",
        human_label=label,
        unit_type=unit_type,
        capability_type=capability_type,
        action_key=action_key,
        supported_scope_kinds=list(scopes),
        required_selector_shape=list(selector_shape),
        branch_policy=branch_policy,
        mutation_class=mutation_class,
        approval_required=approval_required,
        readiness_source=readiness_source,
        expected_receipt_type=expected_receipt_type,
        process_area=process_area or _infer_process_area(action_key, workflow_family),
        produced_artifact_statuses=list(artifact_statuses),
        legal_next_action_relationships=list(relationships),
        child_actions=list(child_actions),
        refusal_semantics=_refusal("dynamic_readiness_refusal", "not_ready", "scope_mismatch", "lineage_blocked"),
        evidence_sources=[
            _evidence("function", "bookforge.query.actions:list_execution_options"),
            _evidence("cli", "bookforge workflow legal-actions"),
        ],
        details=merged_details,
    )


